//! Emitters for the capability catalog consumers outside the agent and GCS:
//! the plugin SDK id list, the MCP server's capability floor, and the JSON
//! catalog the documentation reference is rendered from.

use crate::{esc, Cap, Catalog, GENERATED_HEADER};

/// Escape a string for a JSON string literal.
fn json_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Every capability id a plugin manifest may name (agent and GCS halves),
/// sorted and de-duplicated.
fn all_ids(cat: &Catalog) -> Vec<&str> {
    let mut ids: Vec<&str> = cat
        .agent
        .iter()
        .chain(cat.gcs.iter())
        .map(|c| c.id.as_str())
        .collect();
    ids.sort_unstable();
    ids.dedup();
    ids
}

/// `{"schema":1,"capabilities":[...]}` sorted by id. Agent rows carry their
/// `enforced` flag; GCS rows are enforced by the GCS host, which the catalog
/// does not record, so their `enforced` is `null`.
pub fn emit_capabilities_json(cat: &Catalog) -> String {
    let mut rows: Vec<(&Cap, &str)> = cat
        .agent
        .iter()
        .map(|c| (c, "agent"))
        .chain(cat.gcs.iter().map(|c| (c, "gcs")))
        .collect();
    rows.sort_by(|a, b| a.0.id.cmp(&b.0.id).then(a.1.cmp(b.1)));
    let mut out = String::from("{\n  \"schema\": 1,\n  \"capabilities\": [");
    for (i, (c, side)) in rows.iter().enumerate() {
        let enforced = if *side == "agent" {
            c.enforced.to_string()
        } else {
            "null".to_string()
        };
        out.push_str(if i == 0 { "\n" } else { ",\n" });
        out.push_str(&format!(
            "    {{\"id\": {}, \"label\": {}, \"description\": {}, \"category\": {}, \
             \"risk\": {}, \"enforced\": {enforced}, \"side\": {}}}",
            json_str(&c.id),
            json_str(&c.label),
            json_str(&c.description),
            json_str(&c.category),
            json_str(&c.risk),
            json_str(side),
        ));
    }
    out.push_str("\n  ]\n}\n");
    out
}

/// `capabilities.generated.ts` for the plugin SDK.
pub fn emit_sdk_capabilities(cat: &Catalog) -> String {
    let mut out = format!("// @generated by {GENERATED_HEADER}\n\n");
    out.push_str("export const CAPABILITY_IDS = [\n");
    for id in all_ids(cat) {
        out.push_str(&format!("  \"{}\",\n", esc(id)));
    }
    out.push_str("] as const;\n\n");
    out.push_str("export type CapabilityId = (typeof CAPABILITY_IDS)[number];\n\n");
    out.push_str("export const PLUGIN_SCOPED_PREFIX = \"plugin.\";\n");
    out
}

/// The floor an MCP token needs to reach a capability: `flight` for a
/// flight-control capability that is not a `.read`, `admin` for `hardware.*`.
pub fn floor_for(c: &Cap) -> Option<&'static str> {
    if c.id.starts_with("hardware.") {
        Some("admin")
    } else if c.category == "flight_control" && !c.id.ends_with(".read") {
        Some("flight")
    } else {
        None
    }
}

/// `capability-floor.generated.ts` for the MCP server (agent capabilities).
pub fn emit_mcp_floor(cat: &Catalog) -> String {
    let mut rows: Vec<(&str, &str)> = cat
        .agent
        .iter()
        .filter_map(|c| floor_for(c).map(|f| (c.id.as_str(), f)))
        .collect();
    rows.sort_unstable();
    let mut out = format!("// @generated by {GENERATED_HEADER}\n\n");
    out.push_str(
        "export const CAPABILITY_FLOOR: Readonly<Record<string, \"flight\" | \"admin\">> = {\n",
    );
    for (id, floor) in rows {
        out.push_str(&format!("  \"{}\": \"{floor}\",\n", esc(id)));
    }
    out.push_str("};\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cap(id: &str, category: &str, enforced: bool) -> Cap {
        Cap {
            id: id.into(),
            label: "L".into(),
            description: "say \"hi\"\n".into(),
            category: category.into(),
            risk: "low".into(),
            risk_reason: "r".into(),
            enforced,
        }
    }

    fn sample() -> Catalog {
        Catalog {
            agent: vec![
                cap("mavlink.write", "flight_control", true),
                cap("mavlink.read", "flight_control", true),
                cap("hardware.uart", "hardware", true),
                cap("event.publish", "data_network", true),
            ],
            gcs: vec![cap("ui.map.overlay", "ui_slot", false)],
            method: vec![],
        }
    }

    #[test]
    fn floor_rule_matches_category_and_prefix() {
        let ts = emit_mcp_floor(&sample());
        assert!(ts.contains("\"mavlink.write\": \"flight\""));
        assert!(ts.contains("\"hardware.uart\": \"admin\""));
        assert!(!ts.contains("mavlink.read"));
        assert!(!ts.contains("event.publish"));
    }

    #[test]
    fn sdk_ids_are_sorted_and_cover_both_halves() {
        let ts = emit_sdk_capabilities(&sample());
        let ev = ts.find("\"event.publish\"").unwrap();
        let ui = ts.find("\"ui.map.overlay\"").unwrap();
        assert!(ev < ui);
        assert!(ts.contains("export const PLUGIN_SCOPED_PREFIX = \"plugin.\";"));
        assert!(ts.contains("export type CapabilityId"));
    }

    #[test]
    fn capabilities_json_is_sorted_and_escaped() {
        let j = emit_capabilities_json(&sample());
        assert!(j.starts_with("{\n  \"schema\": 1,"));
        assert!(j.contains("say \\\"hi\\\"\\n"));
        let a = j.find("\"event.publish\"").unwrap();
        let b = j.find("\"mavlink.read\"").unwrap();
        assert!(a < b);
        assert!(j.contains("\"enforced\": null, \"side\": \"gcs\""));
        assert_eq!(json_str("\u{1}"), "\"\\u0001\"");
    }
}
