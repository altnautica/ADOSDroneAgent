//! Generates the ADOS capability catalog for all three languages from a single
//! `capabilities.toml` source of truth, so the Python agent catalog, the Rust
//! `ados-protocol` catalog, and the two TypeScript GCS catalogs cannot drift.
//! It also turns the committed `schemas/api/*.schema.json` files into the
//! agent API TypeScript types the web apps and Mission Control import.
//!
//! Usage:
//!   cargo run -p ados-capabilities-codegen            # write all targets
//!   cargo run -p ados-capabilities-codegen -- --check # verify, non-zero on drift
//!   cargo run -p ados-capabilities-codegen -- --emit-capabilities-json <path>
//!                                                     # write the JSON catalog only
//!
//! Targets whose repository is not checked out (e.g. the GCS, Extensions or
//! MCP sibling in a standalone agent clone) are skipped.

