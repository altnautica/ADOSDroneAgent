//! The runtime path registry emitters: `ados_protocol::paths` (Rust) and
//! `ados.core._paths_generated` (Python), both from the `[[sidecar]]` and
//! `[[socket]]` rows of `contracts.toml`.
//!
//! The registry names every sidecar and socket file once, with the run
//! directory resolver (`ADOS_RUN_DIR`, default `/run/ados`) and each sidecar's
//! freshness window, so no crate re-declares a path or a staleness budget.

use serde::Deserialize;

use crate::{esc, generated_header_for};

/// The default run directory every `/run/ados/...` registry path resolves under.
const RUN_DIR_DEFAULT: &str = "/run/ados";

/// One versioned on-disk state sidecar (a JSON file one service writes and
/// another reads). `path` is the sidecar's default filesystem location.
#[derive(Debug, Deserialize)]
pub struct SidecarRow {
    pub id: String,
    pub version: u16,
    pub path: String,
    /// The freshness window in milliseconds, or `None` for a sidecar whose
    /// mtime is not its age (written on change, or persistent).
    #[serde(default)]
    pub max_age_ms: Option<u64>,
    /// The service that writes the file.
    pub writer: String,
    #[serde(default)]
    pub rust_const: Option<String>,
    #[serde(default)]
    pub description: Option<String>,
}

/// One Unix socket and the service that binds it.
#[derive(Debug, Deserialize)]
pub struct SocketRow {
    pub id: String,
    pub path: String,
    pub owner: String,
}

/// The file name a registry path names (its last segment).
fn file_name(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

/// Whether the path carries a `<placeholder>` segment (a per-instance name).
fn templated(path: &str) -> bool {
    path.contains('<')
}

/// The SCREAMING_SNAKE stem a registry id becomes in a constant name.
fn const_stem(id: &str) -> String {
    id.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

/// Validate the path rows: unique ids across sidecars and sockets, absolute
/// paths, a `.json` sidecar file, a `.sock` socket file, a non-empty writer and
/// owner, and a positive freshness window.
pub fn validate(sidecars: &[SidecarRow], sockets: &[SocketRow]) -> Result<(), Vec<String>> {
    let mut problems = Vec::new();
    let mut seen = std::collections::HashSet::new();
    for id in sidecars
        .iter()
        .map(|s| &s.id)
        .chain(sockets.iter().map(|s| &s.id))
    {
        if !seen.insert(id.as_str()) {
            problems.push(format!("duplicate sidecar/socket id {id:?}"));
        }
    }
    for s in sidecars {
        if !s.path.starts_with('/') {
            problems.push(format!(
                "sidecar {:?}: path {:?} is not absolute",
                s.id, s.path
            ));
        }
        if !s.path.ends_with(".json") {
            problems.push(format!(
                "sidecar {:?}: path {:?} is not a .json file",
                s.id, s.path
            ));
        }
        if s.writer.trim().is_empty() {
            problems.push(format!("sidecar {:?}: empty writer", s.id));
        }
        if s.max_age_ms == Some(0) {
            problems.push(format!("sidecar {:?}: max_age_ms must be positive", s.id));
        }
    }
    for s in sockets {
        if !s.path.starts_with(&format!("{RUN_DIR_DEFAULT}/")) || !s.path.ends_with(".sock") {
            problems.push(format!(
                "socket {:?}: path {:?} is not a /run/ados/*.sock",
                s.id, s.path
            ));
        }
        if s.owner.trim().is_empty() {
            problems.push(format!("socket {:?}: empty owner", s.id));
        }
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems)
    }
}

fn rust_opt_u64(v: Option<u64>) -> String {
    match v {
        Some(n) => format!("Some({n})"),
        None => "None".to_string(),
    }
}

/// Emit `crates/ados-protocol/src/paths.rs`.
pub fn emit_rust(sidecars: &[SidecarRow], sockets: &[SocketRow]) -> String {
    let header = generated_header_for("contracts.toml");
    let mut o = String::new();
    o.push_str(&format!("// @generated by {header}\n"));
    o.push_str("//! Generated runtime path registry.\n//!\n");
    o.push_str("//! Every sidecar and socket file the agent's services share, named once,\n");
    o.push_str("//! with the run-directory resolver and each sidecar's freshness window.\n");
    o.push_str("//! Source: contracts.toml; run ados-capabilities-codegen.\n\n");
    o.push_str("use std::path::PathBuf;\nuse std::time::Duration;\n\n");
    o.push_str("/// The run directory when `ADOS_RUN_DIR` is unset or empty.\n");
    o.push_str(&format!(
        "pub const RUN_DIR_DEFAULT: &str = \"{RUN_DIR_DEFAULT}\";\n\n"
    ));
    o.push_str("/// The environment variable that relocates the run directory.\n");
    o.push_str("pub const RUN_DIR_ENV: &str = \"ADOS_RUN_DIR\";\n\n");

    o.push_str("/// One registered state sidecar.\n");
    o.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
    o.push_str("pub struct SidecarPath {\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    /// The default absolute path.\n");
    o.push_str("    pub path: &'static str,\n");
    o.push_str("    /// The freshness window in milliseconds; `None` when mtime is not age.\n");
    o.push_str("    pub max_age_ms: Option<u64>,\n");
    o.push_str("    /// The service that writes the file.\n");
    o.push_str("    pub writer: &'static str,\n");
    o.push_str("}\n\n");
    o.push_str("impl SidecarPath {\n");
    o.push_str("    /// The freshness window, or `None` when the sidecar has none.\n");
    o.push_str("    pub const fn max_age(&self) -> Option<Duration> {\n");
    o.push_str("        match self.max_age_ms {\n");
    o.push_str("            Some(ms) => Some(Duration::from_millis(ms)),\n");
    o.push_str("            None => None,\n");
    o.push_str("        }\n    }\n}\n\n");

    o.push_str("/// One registered Unix socket.\n");
    o.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
    o.push_str("pub struct SocketPath {\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    /// The default absolute path.\n");
    o.push_str("    pub path: &'static str,\n");
    o.push_str("    /// The service that binds the socket.\n");
    o.push_str("    pub owner: &'static str,\n");
    o.push_str("}\n\n");

    o.push_str("// Sidecar file names and freshness windows.\n");
    for s in sidecars {
        let stem = const_stem(&s.id);
        if !templated(&s.path) {
            o.push_str(&format!(
                "pub const {stem}_JSON: &str = \"{}\";\n",
                esc(file_name(&s.path))
            ));
        }
        if let Some(ms) = s.max_age_ms {
            o.push_str(&format!("pub const {stem}_MAX_AGE_MS: u64 = {ms};\n"));
        }
    }
    o.push_str("\n// Socket file names.\n");
    for s in sockets {
        o.push_str(&format!(
            "pub const {}_SOCK: &str = \"{}\";\n",
            const_stem(&s.id),
            esc(file_name(&s.path))
        ));
    }

    o.push_str("\n/// Every registered sidecar.\n#[rustfmt::skip]\n");
    o.push_str("pub const SIDECARS: &[SidecarPath] = &[\n");
    for s in sidecars {
        o.push_str(&format!(
            "    SidecarPath {{ id: \"{}\", path: \"{}\", max_age_ms: {}, writer: \"{}\" }},\n",
            esc(&s.id),
            esc(&s.path),
            rust_opt_u64(s.max_age_ms),
            esc(&s.writer)
        ));
    }
    o.push_str("];\n\n/// Every registered socket.\n#[rustfmt::skip]\n");
    o.push_str("pub const SOCKETS: &[SocketPath] = &[\n");
    for s in sockets {
        o.push_str(&format!(
            "    SocketPath {{ id: \"{}\", path: \"{}\", owner: \"{}\" }},\n",
            esc(&s.id),
            esc(&s.path),
            esc(&s.owner)
        ));
    }
    o.push_str("];\n\n");

    o.push_str(RUST_FNS);
    o
}

const RUST_FNS: &str = r#"/// The run directory: `ADOS_RUN_DIR` when set and non-empty, else
/// [`RUN_DIR_DEFAULT`].
pub fn run_dir() -> PathBuf {
    std::env::var_os(RUN_DIR_ENV)
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(RUN_DIR_DEFAULT))
}

/// The registered sidecar with this id.
pub fn sidecar(id: &str) -> Option<&'static SidecarPath> {
    SIDECARS.iter().find(|s| s.id == id)
}

/// The registered socket with this id.
pub fn socket(id: &str) -> Option<&'static SocketPath> {
    SOCKETS.iter().find(|s| s.id == id)
}

/// Resolve a registry path: a `/run/ados/...` path moves under [`run_dir`], any
/// other absolute path is returned as registered.
pub fn resolve(path: &str) -> PathBuf {
    match path
        .strip_prefix(RUN_DIR_DEFAULT)
        .and_then(|r| r.strip_prefix('/'))
    {
        Some(rest) => run_dir().join(rest),
        None => PathBuf::from(path),
    }
}

/// The resolved path of a registered sidecar or socket id. An id with no
/// registry row is taken as a file name under [`run_dir`], so an unregistered
/// sentinel or journal (`uplink-active`, `mesh-events.jsonl`) resolves the same
/// way.
pub fn run_path(id: &str) -> PathBuf {
    match sidecar(id)
        .map(|s| s.path)
        .or_else(|| socket(id).map(|s| s.path))
    {
        Some(path) => resolve(path),
        None => run_dir().join(id),
    }
}

/// The freshness window of a registered sidecar, or `None` when the id is not
/// registered or the sidecar has no window.
pub fn max_age(id: &str) -> Option<Duration> {
    sidecar(id).and_then(SidecarPath::max_age)
}
"#;

fn py_opt_u64(v: Option<u64>) -> String {
    match v {
        Some(n) => n.to_string(),
        None => "None".to_string(),
    }
}

/// Emit `src/ados/core/_paths_generated.py`.
pub fn emit_python(sidecars: &[SidecarRow], sockets: &[SocketRow]) -> String {
    let header = generated_header_for("contracts.toml");
    let mut o = String::new();
    o.push_str(&format!("# @generated by {header}\n"));
    o.push_str("\"\"\"Generated runtime path registry.\n\n");
    o.push_str("Every sidecar and socket file the agent's services share, named once,\n");
    o.push_str("with the run-directory resolver and each sidecar's freshness window.\n");
    o.push_str("Source: crates/ados-protocol/contracts.toml.\n\"\"\"\n\n");
    o.push_str("from __future__ import annotations\n\nimport os\nfrom pathlib import Path\n\n");
    o.push_str(&format!("RUN_DIR_DEFAULT = \"{RUN_DIR_DEFAULT}\"\n"));
    o.push_str("RUN_DIR_ENV = \"ADOS_RUN_DIR\"\n\n");
    for s in sidecars {
        let stem = const_stem(&s.id);
        if !templated(&s.path) {
            o.push_str(&format!("{stem}_JSON = \"{}\"\n", esc(file_name(&s.path))));
        }
        if let Some(ms) = s.max_age_ms {
            o.push_str(&format!("{stem}_MAX_AGE_MS = {ms}\n"));
        }
    }
    o.push('\n');
    for s in sockets {
        o.push_str(&format!(
            "{}_SOCK = \"{}\"\n",
            const_stem(&s.id),
            esc(file_name(&s.path))
        ));
    }
    o.push_str("\nSIDECAR_PATHS: dict[str, dict[str, object]] = {\n");
    for s in sidecars {
        o.push_str(&format!(
            "    \"{}\": {{\"path\": \"{}\", \"max_age_ms\": {}, \"writer\": \"{}\"}},\n",
            esc(&s.id),
            esc(&s.path),
            py_opt_u64(s.max_age_ms),
            esc(&s.writer)
        ));
    }
    o.push_str("}\n\nSOCKET_PATHS: dict[str, dict[str, str]] = {\n");
    for s in sockets {
        o.push_str(&format!(
            "    \"{}\": {{\"path\": \"{}\", \"owner\": \"{}\"}},\n",
            esc(&s.id),
            esc(&s.path),
            esc(&s.owner)
        ));
    }
    o.push_str("}\n\n");
    o.push_str(PY_FNS);
    o
}

const PY_FNS: &str = r#"
def run_dir() -> Path:
    """The run directory: ``ADOS_RUN_DIR`` when set and non-empty, else the default."""
    return Path(os.environ.get(RUN_DIR_ENV) or RUN_DIR_DEFAULT)


def resolve(path: str) -> Path:
    """Move a ``/run/ados/...`` registry path under :func:`run_dir`; keep any other."""
    prefix = RUN_DIR_DEFAULT + "/"
    if path.startswith(prefix):
        return run_dir() / path[len(prefix) :]
    return Path(path)


def run_path(entry_id: str) -> Path:
    """The resolved path of a registered sidecar or socket id.

    An id with no registry row is taken as a file name under :func:`run_dir`.
    """
    row = SIDECAR_PATHS.get(entry_id) or SOCKET_PATHS.get(entry_id)
    if row is None:
        return run_dir() / entry_id
    return resolve(str(row["path"]))
"#;

#[cfg(test)]
mod tests {
    use super::*;

    fn rows() -> (Vec<SidecarRow>, Vec<SocketRow>) {
        (
            vec![
                SidecarRow {
                    id: "wfb-stats".into(),
                    version: 1,
                    path: "/run/ados/wfb-stats.json".into(),
                    max_age_ms: Some(10_000),
                    writer: "ados-radio".into(),
                    rust_const: None,
                    description: None,
                },
                SidecarRow {
                    id: "config-status".into(),
                    version: 1,
                    path: "/run/ados/config-status-<service>.json".into(),
                    max_age_ms: None,
                    writer: "ados-config".into(),
                    rust_const: None,
                    description: None,
                },
            ],
            vec![SocketRow {
                id: "hid-cmd".into(),
                path: "/run/ados/hid-cmd.sock".into(),
                owner: "ados-hid".into(),
            }],
        )
    }

    #[test]
    fn rust_paths_carry_consts_tables_and_resolvers() {
        let (sc, so) = rows();
        let rs = emit_rust(&sc, &so);
        assert!(rs.contains("pub const WFB_STATS_JSON: &str = \"wfb-stats.json\";"));
        assert!(rs.contains("pub const WFB_STATS_MAX_AGE_MS: u64 = 10000;"));
        assert!(rs.contains("pub const HID_CMD_SOCK: &str = \"hid-cmd.sock\";"));
        // A templated path has no file-name const.
        assert!(!rs.contains("CONFIG_STATUS_JSON"));
        assert!(rs.contains("max_age_ms: None, writer: \"ados-config\""));
        assert!(rs.contains("pub fn run_dir() -> PathBuf"));
        assert!(rs.contains("pub fn run_path(id: &str) -> PathBuf"));
    }

    #[test]
    fn python_paths_carry_the_same_rows() {
        let (sc, so) = rows();
        let py = emit_python(&sc, &so);
        assert!(py.contains("WFB_STATS_JSON = \"wfb-stats.json\""));
        assert!(py.contains(
            "\"wfb-stats\": {\"path\": \"/run/ados/wfb-stats.json\", \"max_age_ms\": 10000"
        ));
        assert!(py.contains(
            "\"hid-cmd\": {\"path\": \"/run/ados/hid-cmd.sock\", \"owner\": \"ados-hid\"}"
        ));
        assert!(py.contains("def run_path(entry_id: str) -> Path:"));
    }

    #[test]
    fn validate_rejects_duplicates_and_bad_paths() {
        let (mut sc, mut so) = rows();
        assert!(validate(&sc, &so).is_ok());
        so.push(SocketRow {
            id: "wfb-stats".into(),
            path: "/tmp/x.sock".into(),
            owner: String::new(),
        });
        sc[0].max_age_ms = Some(0);
        let problems = validate(&sc, &so).unwrap_err();
        assert!(problems.iter().any(|p| p.contains("duplicate")));
        assert!(problems
            .iter()
            .any(|p| p.contains("not a /run/ados/*.sock")));
        assert!(problems.iter().any(|p| p.contains("empty owner")));
        assert!(problems.iter().any(|p| p.contains("must be positive")));
    }

    #[test]
    fn const_stem_maps_separators() {
        assert_eq!(const_stem("wfb_failover"), "WFB_FAILOVER");
        assert_eq!(const_stem("lcd-fb-stats"), "LCD_FB_STATS");
    }
}
