//! JSON Schema → TypeScript for the agent's REST and heartbeat wire types.
//!
//! The inputs are the committed `schemas/api/*.schema.json` files: two written
//! by the Rust crates' schema tests (schemars) and one by
//! `scripts/emit_api_schemas.py` (Pydantic). Each file's root becomes a named
//! export under the name its caller gives, and every `$defs` entry becomes a
//! named export under its own name.
//!
//! Only the subset those producers emit is understood: `type` (single or a
//! list), `properties` + `required`, `additionalProperties`, `items`, `enum`,
//! `const`, `anyOf`/`oneOf`, a single-element `allOf`, `$ref` into `$defs` or
//! `definitions`, and the `true` schema. Annotation keywords are ignored. Any
//! other keyword panics, so a producer change the emitter cannot express
//! stops the codegen instead of generating a type that silently lies.

use std::collections::BTreeMap;

use serde_json::{Map, Value};

use crate::generated_header_for;

/// One schema file and the exported name of its root type.
#[derive(Clone, Copy)]
pub(crate) struct ApiSchema<'a> {
    /// The repo-relative file name, used in messages.
    pub file: &'a str,
    pub root: &'a str,
    pub schema: &'a Value,
}

/// Keywords that carry no type information.
const ANNOTATIONS: &[&str] = &[
    "$schema",
    "title",
    "description",
    "default",
    "examples",
    "format",
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "readOnly",
    "writeOnly",
    "deprecated",
];

/// Keywords this emitter turns into types.
const TYPED: &[&str] = &[
    "type",
    "properties",
    "required",
    "additionalProperties",
    "items",
    "enum",
    "const",
    "anyOf",
    "oneOf",
    "allOf",
    "$ref",
];

/// The TypeScript module for `schemas`. `source` names the inputs in the
/// generated header.
pub(crate) fn emit_ts_api_types(schemas: &[ApiSchema<'_>], source: &str) -> String {
    let mut roots = Vec::new();
    let mut defs: BTreeMap<String, (String, &str)> = BTreeMap::new();
    for s in schemas {
        roots.push(named(s.root, s.schema, s.file, true));
        for key in ["$defs", "definitions"] {
            let Some(found) = s.schema.get(key) else {
                continue;
            };
            let found = found
                .as_object()
                .unwrap_or_else(|| panic!("{key} in {} is not an object", s.file));
            for (name, node) in found {
                let text = named(name, node, s.file, false);
                match defs.get(name) {
                    Some((prev, prev_file)) if *prev != text => panic!(
                        "definition {name} differs between {prev_file} and {}",
                        s.file
                    ),
                    _ => {
                        defs.insert(name.clone(), (text, s.file));
                    }
                }
            }
        }
    }
    let mut out = format!("// @generated by {}\n", generated_header_for(source));
    for block in roots.iter().chain(defs.values().map(|(t, _)| t)) {
        out.push('\n');
        out.push_str(block);
    }
    out
}

/// A named export: an `interface` for an object with properties, otherwise a
/// `type` alias.
fn named(name: &str, node: &Value, file: &str, root: bool) -> String {
    let obj = node.as_object();
    let props = obj
        .and_then(|o| o.get("properties"))
        .and_then(Value::as_object);
    match (obj, props) {
        (Some(o), Some(props)) if !has_union(o) => {
            check_keywords(o, file, root);
            let mut out = format!("export interface {name} {{\n");
            for line in members(o, props, file) {
                out.push_str(&format!("  {line};\n"));
            }
            out.push_str("}\n");
            out
        }
        _ => {
            if let (true, Some(o)) = (root, obj) {
                check_keywords(o, file, root);
            }
            format!("export type {name} = {};\n", ts_type(node, file))
        }
    }
}

fn has_union(o: &Map<String, Value>) -> bool {
    ["anyOf", "oneOf", "enum", "const", "$ref"]
        .iter()
        .any(|k| o.contains_key(*k))
}

/// The member lines of an object schema: one per property (optional unless
/// required), plus an index signature for open objects.
fn members(o: &Map<String, Value>, props: &Map<String, Value>, file: &str) -> Vec<String> {
    let required: Vec<&str> = o
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut lines: Vec<String> = props
        .iter()
        .map(|(key, schema)| {
            let opt = if required.contains(&key.as_str()) {
                ""
            } else {
                "?"
            };
            format!("{}{opt}: {}", prop_key(key), ts_type(schema, file))
        })
        .collect();
    match o.get("additionalProperties") {
        None | Some(Value::Bool(false)) => {}
        Some(extra) if is_any(extra) => lines.push("[key: string]: unknown".to_string()),
        Some(_) => panic!("typed additionalProperties beside properties in {file}"),
    }
    lines
}

/// Whether `node` accepts any value (`true` or `{}`).
fn is_any(node: &Value) -> bool {
    match node {
        Value::Bool(b) => *b,
        Value::Object(o) => o.keys().all(|k| ANNOTATIONS.contains(&k.as_str())),
        _ => false,
    }
}

fn check_keywords(o: &Map<String, Value>, file: &str, root: bool) {
    for k in o.keys() {
        let root_only = root && (k == "$defs" || k == "definitions");
        if !root_only && !ANNOTATIONS.contains(&k.as_str()) && !TYPED.contains(&k.as_str()) {
            panic!("unsupported JSON Schema keyword {k} in {file}");
        }
    }
}

/// The TypeScript type expression for one schema node.
fn ts_type(node: &Value, file: &str) -> String {
    let o = match node {
        Value::Bool(true) => return "unknown".to_string(),
        Value::Bool(false) => return "never".to_string(),
        Value::Object(o) => o,
        other => panic!("schema node {other} in {file} is not an object"),
    };
    check_keywords(o, file, false);
    if let Some(r) = o.get("$ref").and_then(Value::as_str) {
        return ref_name(r, file);
    }
    if let Some(all) = o.get("allOf") {
        match all.as_array().map(Vec::as_slice) {
            Some([single]) => return ts_type(single, file),
            _ => panic!("unsupported JSON Schema keyword allOf (more than one member) in {file}"),
        }
    }
    if let Some(c) = o.get("const") {
        return literal(c, file);
    }
    if let Some(values) = o.get("enum").and_then(Value::as_array) {
        return union(values.iter().map(|v| literal(v, file)).collect());
    }
    if let Some(members) = o.get("anyOf").or_else(|| o.get("oneOf")) {
        let members = members
            .as_array()
            .unwrap_or_else(|| panic!("anyOf/oneOf in {file} is not an array"));
        return union(members.iter().map(|m| ts_type(m, file)).collect());
    }
    match o.get("type") {
        None => "unknown".to_string(),
        Some(Value::String(t)) => primitive(t, o, file),
        Some(Value::Array(types)) => union(
            types
                .iter()
                .map(|t| {
                    let t = t
                        .as_str()
                        .unwrap_or_else(|| panic!("non-string type in {file}"));
                    primitive(t, o, file)
                })
                .collect(),
        ),
        Some(other) => panic!("type {other} in {file} is neither a string nor a list"),
    }
}

fn primitive(t: &str, o: &Map<String, Value>, file: &str) -> String {
    match t {
        "string" => "string".to_string(),
        "integer" | "number" => "number".to_string(),
        "boolean" => "boolean".to_string(),
        "null" => "null".to_string(),
        "array" => match o.get("items") {
            Some(items) => array_of(ts_type(items, file)),
            None => "unknown[]".to_string(),
        },
        "object" => object_literal(o, file),
        other => panic!("unsupported JSON Schema type {other} in {file}"),
    }
}

fn object_literal(o: &Map<String, Value>, file: &str) -> String {
    if let Some(props) = o.get("properties").and_then(Value::as_object) {
        return format!("{{ {} }}", members(o, props, file).join("; "));
    }
    match o.get("additionalProperties") {
        Some(Value::Bool(false)) => "Record<string, never>".to_string(),
        Some(extra) if !is_any(extra) => format!("Record<string, {}>", ts_type(extra, file)),
        _ => "Record<string, unknown>".to_string(),
    }
}

fn array_of(item: String) -> String {
    if item.contains(' ') && !item.starts_with('{') {
        format!("({item})[]")
    } else {
        format!("{item}[]")
    }
}

/// `a | b`, without duplicate members.
fn union(members: Vec<String>) -> String {
    let mut seen: Vec<String> = Vec::new();
    for m in members {
        if !seen.contains(&m) {
            seen.push(m);
        }
    }
    seen.join(" | ")
}

fn literal(v: &Value, file: &str) -> String {
    match v {
        Value::String(_) | Value::Number(_) | Value::Bool(_) | Value::Null => v.to_string(),
        other => panic!("non-scalar enum/const value {other} in {file}"),
    }
}

fn ref_name(r: &str, file: &str) -> String {
    r.strip_prefix("#/$defs/")
        .or_else(|| r.strip_prefix("#/definitions/"))
        .unwrap_or_else(|| panic!("unsupported $ref {r} in {file}"))
        .to_string()
}

/// A property name, quoted unless it is a plain identifier.
fn prop_key(key: &str) -> String {
    let mut chars = key.chars();
    let ident = chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ident {
        key.to_string()
    } else {
        Value::String(key.to_string()).to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn emit(schema: &Value) -> String {
        emit_ts_api_types(
            &[ApiSchema {
                file: "t.json",
                root: "Root",
                schema,
            }],
            "t.json",
        )
    }

    #[test]
    fn objects_unions_refs_and_open_maps() {
        let schema = json!({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "title": "Ignored",
            "type": "object",
            "properties": {
                "a": {"type": "string"},
                "b": {"type": ["integer", "null"], "format": "int64"},
                "c": {"anyOf": [{"$ref": "#/$defs/Leaf"}, {"type": "null"}]},
                "d": {"type": "array", "items": {"type": ["string", "null"]}},
                "e": true,
                "f": {"type": "object", "additionalProperties": {"type": "string"}},
                "g": {"enum": ["x", "y"], "type": "string"},
                "h": {"allOf": [{"$ref": "#/$defs/Leaf"}], "default": {}},
                "kebab-key": {"const": 3}
            },
            "required": ["a", "b"],
            "additionalProperties": true,
            "$defs": {"Leaf": {"type": "object", "properties": {"z": {"type": "boolean"}}, "required": ["z"]}}
        });
        assert_eq!(
            emit(&schema),
            "// @generated by ados-capabilities-codegen from t.json. Do not edit by hand.\n\n\
             export interface Root {\n  a: string;\n  b: number | null;\n  c?: Leaf | null;\n  \
             d?: (string | null)[];\n  e?: unknown;\n  f?: Record<string, string>;\n  \
             g?: \"x\" | \"y\";\n  h?: Leaf;\n  \"kebab-key\"?: 3;\n  [key: string]: unknown;\n}\n\n\
             export interface Leaf {\n  z: boolean;\n}\n"
        );
    }

    #[test]
    fn a_non_object_definition_is_a_type_alias() {
        let schema = json!({
            "type": "object",
            "properties": {"s": {"$ref": "#/$defs/State"}},
            "$defs": {"State": {"enum": ["on", "off"], "title": "State", "type": "string"}}
        });
        assert!(emit(&schema).contains("export type State = \"on\" | \"off\";\n"));
    }

    #[test]
    #[should_panic(expected = "unsupported JSON Schema keyword patternProperties in t.json")]
    fn an_unknown_keyword_panics() {
        emit(&json!({"type": "object", "properties": {"p": {"patternProperties": {}}}}));
    }

    #[test]
    #[should_panic(expected = "definition Leaf differs")]
    fn conflicting_definitions_panic() {
        let a = json!({"type": "object", "properties": {}, "$defs": {"Leaf": {"type": "string"}}});
        let b = json!({"type": "object", "properties": {}, "$defs": {"Leaf": {"type": "number"}}});
        emit_ts_api_types(
            &[
                ApiSchema {
                    file: "a.json",
                    root: "A",
                    schema: &a,
                },
                ApiSchema {
                    file: "b.json",
                    root: "B",
                    schema: &b,
                },
            ],
            "a.json, b.json",
        );
    }
}
