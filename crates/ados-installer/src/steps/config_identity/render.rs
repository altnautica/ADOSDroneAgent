/// Build the `network` config block carrying the operating-region posture
/// (pure). Default is unrestricted: the radio transmits without pinning a
/// country, and the operator is responsible for local radio rules (the note is
/// written honestly, it never claims compliance). A pinned region records the
/// country plus an install-time acknowledgement stamp. Only `network.regulatory`
/// is set here; the agent deep-merges the rest of the network defaults.
pub fn regulatory_block(region: Option<&str>, ack_at: &str) -> String {
    match region {
        Some(code) => format!(
            "network:\n  \
# Operating region for the long-range radio. A region is pinned, so the radio\n  \
# applies this country's channels and power limits before it transmits.\n  \
regulatory:\n    \
mode: \"region\"\n    \
region: \"{code}\"\n    \
ack_operator: \"installer\"\n    \
ack_at: \"{ack_at}\"\n"
        ),
        None => "network:\n  \
# Operating region for the long-range radio. Default is unrestricted: the radio\n  \
# transmits on your channel at the device's power budget without pinning a\n  \
# country. You are responsible for the radio rules where you fly. Pin a region\n  \
# here or in the app to apply that country's channel and power limits.\n  \
regulatory:\n    \
mode: \"unrestricted\"\n    \
region: null\n    \
ack_operator: null\n    \
ack_at: null\n"
            .to_string(),
    }
}

/// Build the `profile.conf` body (pure).
///
/// Carries the install identity an upgrade must preserve: the profile, the
/// release channel, and, on a pinned channel, the version. Recording the
/// channel is what stops a device installed on `stable` defecting to
/// tip-of-main on its first update and losing signature enforcement with it,
/// which is channel-gated.
pub fn profile_conf_body(profile: &str, channel: &str, version: Option<&str>) -> String {
    let mut body = format!("profile: {profile}\nchannel: {channel}\n");
    if let Some(v) = version {
        body.push_str(&format!("version: {v}\n"));
    }
    body
}

/// Build the `pairing.json` body (pure). The pending API key travels with the
/// code, so the cloud beacon can advertise the code straight away and the
/// later claim persists the same key; `None` leaves the key for the local API
/// to mint.
pub fn pairing_json(code: &str, created_at: u64, pending_api_key: Option<&str>) -> String {
    let body = serde_json::json!({
        "pairing_code": code.to_ascii_uppercase(),
        "code_created_at": created_at,
    });
    let mut body = body.as_object().cloned().unwrap_or_default();
    if let Some(key) = pending_api_key {
        body.insert("pending_api_key".to_string(), serde_json::json!(key));
    }
    let mut out =
        serde_json::to_string_pretty(&serde_json::Value::Object(body)).unwrap_or_default();
    out.push('\n');
    out
}

/// Mint a pending API key in the agent's key format: `"ados_"` plus url-safe
/// base64 (no padding) of 32 random bytes. `None` when the OS RNG fails: a
/// guessable key is worse than none, and the local API mints one later.
pub fn mint_pending_api_key() -> Option<String> {
    use base64::Engine as _;
    let mut bytes = [0u8; 32];
    getrandom::fill(&mut bytes).ok()?;
    Some(format!(
        "ados_{}",
        base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(bytes)
    ))
}

/// Rewrite (or append) the `127.0.1.1 <slug>` line in a `/etc/hosts` body
/// (pure). Replaces an existing `127.0.1.1 ...` line; otherwise appends one.
pub fn rewrite_hosts_body(hosts: &str, slug: &str) -> String {
    let had_trailing_newline = hosts.ends_with('\n');
    let mut found = false;
    let mut out: Vec<String> = Vec::new();
    for raw in hosts.lines() {
        let starts_127011 = raw
            .split_whitespace()
            .next()
            .map(|t| t == "127.0.1.1")
            .unwrap_or(false);
        if starts_127011 {
            out.push(format!("127.0.1.1\t{slug}"));
            found = true;
        } else {
            out.push(raw.to_string());
        }
    }
    if !found {
        out.push(format!("127.0.1.1\t{slug}"));
    }
    let mut joined = out.join("\n");
    if had_trailing_newline || !found {
        joined.push('\n');
    }
    joined
}

/// The `--display` value a profile resolves to when the operator gave none: a
/// ground station and a visor carry a panel as their local UI, so the panel is
/// auto-detected; every other profile gets `none`. Shared with the residue
/// step so the two never disagree.
pub(crate) fn default_display_arg(profile: &str) -> &'static str {
    if matches!(profile, "ground_station" | "visor") {
        "auto"
    } else {
        "none"
    }
}

/// Operator-facing note explaining how to revert the radio services to the
/// packaged Python implementations. Deployed at `/etc/ados/CUTOVER`.
pub(super) const CUTOVER_NOTE_PATH: &str = "/etc/ados/CUTOVER";

/// The body of the CUTOVER note (pure). Every WFB plane — the drone transmit
/// plane, the ground direct-role receive plane, and the mesh relay/receiver
/// roles — is native-only; the packaged Python predecessors were deleted.
pub fn cutover_note_body() -> &'static str {
    "ADOS radio services run native binaries.\n\
\n\
The drone transmit plane, the ground direct-role receive plane, and the mesh\n\
relay and receiver roles are all native-only — there is no Python fallback\n\
for any of them. A missing or broken binary fails loud rather than silently\n\
running a stale implementation.\n"
}
